export function formatLanguageLabel(language: TargetLanguage): string {
  return `${language.name} (${language.nativeName}) · ${language.code}`;
}

export function findTargetLanguage(code: string): TargetLanguage | null {
  const normalized = code.trim().toLowerCase();
  if (!normalized) {
    return null;
  }
  return TARGET_LANGUAGES.find((item) => item.code.toLowerCase() === normalized) ?? null;
}

export function resolveTargetLanguageCode(value: string, fallback = 'zh-CN'): string {
  const trimmed = value.trim();
  if (!trimmed) {
    return fallback;
  }
  const known = findTargetLanguage(trimmed);
  return known?.code ?? trimmed;
}
